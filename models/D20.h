/**
 ****************************************************************************************************
 * @file        D20.h
 * @brief       骰子模型 D20: 正二十面体(1~20 点), 可投放任意多颗
 * @note        颜色一律 RGB888; 每颗骰子只给面色, 棱边色/点数色由 D20.c 自动配。
 ****************************************************************************************************
 */

#ifndef __D20_H
#define __D20_H

#include "Dice.h"

/******************************************************************************************/
/* 演示用配色(RGB888; 应用可以全部自己传, 这里只是默认值) */

#define D20_BG_COLOR        0x0A0F1A      /* 屏幕底色 = 骰子每帧擦除用的背景色 */
#define D20_SHADOW_OUT      0x080818      /* 地面阴影外圈 */
#define D20_SHADOW_IN       0x000810      /* 地面阴影内圈 */
#define D20_FACE_COLOR      0x693CD1      /* 默认面色: 紫罗兰 */
#define D20_TITLE_COLOR     0x79BEFF      /* 标题颜色 */
#define D20_INFO_COLOR      0x8A93B8      /* 说明文字颜色 */

/******************************************************************************************/
/* 渲染参数 */

/* 几何决定的投影峰值(实测约1.033, 不要改小); 相机距离/光照/点数等通用常量在 Dice.h 的 DICE_* */
#define D20_PROJ_PEAK       1.05f       /* 投影半径峰值 / scale(几何决定, 实测约1.033, 不要改小) */
#define D20_CONTACT_K       0.88f       /* 互撞判定半径 = 直径/2 × 这个系数(轮廓 0.79~1.0 的折中) */
#define D20_SHOW_NUM        1           /* 1:可见面上画点数; 0:只画纯色面(更省CPU) */

/* 地面阴影是每颗骰子的开关(不是全局宏): dice_t.flags 里带 DICE_FLAG_SHADOW 才画, 见 Dice.h */

/******************************************************************************************/
/* 角速度(弧度/秒): 实际转速 = 参数 x dice_t.speed。库按真实时间积分, 掉帧也不会变慢 */

#define D20_SPIN_X          1.6875f     /* 绕X轴(原 0.0135 弧度/帧 @125fps) */
#define D20_SPIN_Y          2.5000f     /* 绕Y轴(原 0.0200 弧度/帧) */
#define D20_SPIN_Z          0.9375f     /* 绕Z轴(原 0.0075 弧度/帧) */

/******************************************************************************************/
/* 模型描述: 传给 dice_init() 选用这颗骰子 */

extern const dice_model_t dice_d20;

#endif
