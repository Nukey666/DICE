/**
 ****************************************************************************************************
 * @file        D6.h
 * @brief       骰子模型 D6: 立方体(1~6 点), 可投放任意多颗
 * @note        颜色一律 RGB888; 每颗骰子只给面色, 棱边色/点数色由 D6.c 自动配。
 ****************************************************************************************************
 */

#ifndef __D6_H
#define __D6_H

#include "Dice.h"

/******************************************************************************************/
/* 演示用配色(RGB888; 应用可以全部自己传, 这里只是默认值) */

#define D6_BG_COLOR         0x0A0F1A      /* 面板底色, 必须和 D20_BG_COLOR 一致(整屏只有一种底色) */
#define D6_SHADOW_OUT       0x080818      /* 地面阴影外圈 */
#define D6_SHADOW_IN        0x000810      /* 地面阴影内圈 */
#define D6_FACE_COLOR       0xE8E4D8      /* 默认面色: 象牙白 */

/******************************************************************************************/
/* 渲染参数 */

/* 顶点全在外接球上的多面体, 投影峰值恒为 1.0338(Dice.h 第 5 节算法), 取 1.05 就够 */
#define D6_PROJ_PEAK        1.05f

/* 面比 D20 的三角形大得多, 点数门限要跟着放大: 约等于"面的投影高度放得下字",
   否则面很斜的时候数字会压到棱外面去(D20 用 0.19, 那是按单个三角形算的) */
#define D6_NUM_AREA_K       1.20f

/* 互撞判定半径 = 直径/2 × 这个系数(立方体轮廓 0.82~1.00, 取中间偏保守) */
#define D6_CONTACT_K        0.90f

/* 地面减速度(px/s²): 立方体滑一小段就站住; D20 是 18, 面越多滚得越久 */
#define D6_FRICTION         32.0f

/******************************************************************************************/
/* 角速度(弧度/秒): 实际转速 = 参数 x 应用传进来的倍率, 符号=转向 */

#define D6_SPIN_X           1.6875f
#define D6_SPIN_Y           2.5000f
#define D6_SPIN_Z           0.9375f

/******************************************************************************************/
/* 模型描述: 传给 dice_spawn() 选用这颗骰子 */

extern const dice_model_t dice_d6;

#endif
